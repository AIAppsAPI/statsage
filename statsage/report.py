"""Report rendering, markdown and self-contained HTML.

The HTML embeds the figure as a base64 data URI and all CSS inline, so
one file can be emailed or attached to a lab notebook. Output is plain
ASCII, angle brackets and ampersands in data values are escaped with
HTML entities.
"""

